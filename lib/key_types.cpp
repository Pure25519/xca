/* Whether this build can generate the keyjob: the type exists in
 * keytype::types() and an EC curve is one of the builtin curves */
static bool generatable(const QString &job)
{
	keyjob j(job);
	if (!j.ktype.isValid())
		return false;
	return !j.isEC() || builtinCurves.containNid(j.ec_nid);
}

QStringList supportedKeyTypes()
{
	QStringList l;
	for (const auto &t : keyTypeTable)
		if (generatable(t.job))
			l << t.name;
	return l;
}

QString keyTypeOf(const EVP_PKEY *pkey)
{
	QString job;
	char group[80];
	size_t len = 0;
	switch (EVP_PKEY_get_base_id(pkey)) {
	case EVP_PKEY_RSA:
		job = QString("RSA:%1").arg(EVP_PKEY_get_bits(pkey));
		break;
	case EVP_PKEY_EC:
		if (EVP_PKEY_get_group_name(pkey, group, sizeof group, &len))
			job = QString("EC:%1").arg(group);
		break;
	default:
		job = EVP_PKEY_get0_type_name(pkey);
	}
	for (const auto &t : keyTypeTable)
		if (job.compare(t.job, Qt::CaseInsensitive) == 0)
			return t.name;
	return QString();
}

QStringList keyTypeNames()
{
	QStringList l;
	for (const auto &t : keyTypeTable)
		l << t.name;
	return l;
}

QString keyTypeFamily(const QString &keyType)
{
	for (const auto &t : keyTypeTable)
		if (keyType == t.name)
			return t.family;
	return QString();
}

QStringList keyFamilies()
{
	QStringList l;
	for (const auto &t : keyTypeTable)
		if (!l.contains(t.family))
			l << t.family;
	return l;
}

bool signatureOnlyFamily(const QString &family)
{
	return family == "eddsa" || family == "ml-dsa" || family == "slh-dsa";
}

QString keyJobText(const QString &keyType)
{
	for (const auto &t : keyTypeTable) {
		if (keyType != t.name)
			continue;
		if (!generatable(t.job))
			throw serviceError("not_supported", QObject::tr(
				"The key type '%1' cannot be generated by this "
				"build; available: %2").arg(keyType)
				.arg(supportedKeyTypes().join(", ")));
		return t.job;
	}
	throw serviceError("invalid_key_type", QObject::tr(
		"Unknown key type '%1'; available: %2").arg(keyType)
		.arg(supportedKeyTypes().join(", ")));
}
